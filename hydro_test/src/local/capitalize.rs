use hydro_lang::live_collections::stream::{AtLeastOnce, NoOrder};
use hydro_lang::prelude::*;

pub fn capitalize<'a>(input: Stream<String, Process<'a, ()>>) {
    input
        .map(q!(|s| s.to_uppercase()))
        .embedded_output("output");
}

/// Like [`capitalize`], but emits an unordered, at-least-once stream, which `embedded_output`
/// also accepts.
pub fn capitalize_unordered<'a>(input: Stream<String, Process<'a, ()>>) {
    input
        .map(q!(|s| s.to_uppercase()))
        .weaken_ordering::<NoOrder>()
        .weaken_retries::<AtLeastOnce>()
        .embedded_output("output");
}

#[cfg(test)]
mod tests {
    use hydro_lang::compile::embedded::EmbeddedCodegenOptions;
    use hydro_lang::location::Location;

    /// Builds the `capitalize` flow and returns the formatted generated embedded source.
    fn capitalize_codegen(options: &EmbeddedCodegenOptions) -> String {
        let mut flow = hydro_lang::compile::builder::FlowBuilder::new();
        let process = flow.process::<()>();
        super::capitalize(process.embedded_input("input"));

        let code = flow
            .with_process(&process, "capitalize")
            .generate_embedded_with_options("hydro_test", options);
        prettyplease::unparse(&code)
    }

    /// Snapshots the Rust source generated by the embedded backend for the simplest embedded
    /// program, so that changes to the DFIR / Hydro codegen output can be reviewed as diffs.
    #[test]
    fn capitalize_embedded_codegen() {
        hydro_build_utils::assert_snapshot!(capitalize_codegen(&EmbeddedCodegenOptions::default()));
    }

    /// Same as [`capitalize_embedded_codegen`], but with per-operator flamegraph attribution
    /// wrappers enabled, to track their cost on the generated code.
    #[test]
    fn capitalize_embedded_codegen_flame_attribution() {
        hydro_build_utils::assert_snapshot!(capitalize_codegen(
            &EmbeddedCodegenOptions::with_flame_attribution()
        ));
    }
}
